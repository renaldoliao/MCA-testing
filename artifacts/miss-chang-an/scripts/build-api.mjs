// Packs the order + chat server into one ready-to-run file (api/index.js) for Vercel.
// Runs automatically before every website build.
import { build } from 'esbuild';
import path from 'node:path';

const here = path.dirname(new URL(import.meta.url).pathname);
await build({
  entryPoints: [path.join(here, 'api-entry.ts')],
  outfile: path.join(here, '..', 'api', 'index.js'),
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  conditions: ['workspace'],
  external: ['pg-native'],
  banner: { js: "// Generated by scripts/build-api.mjs. Do not edit by hand.\nimport { createRequire as __mcaRequire } from 'module'; const require = __mcaRequire(import.meta.url);" },
  logLevel: 'warning',
});
console.log('api/index.js built');
